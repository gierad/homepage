<h2 class="major">SKINTRACK: FREQUENTLY ASKED QUESTIONS</h2>

<blockquote>How is accuracy affected when the watch is reworn?</blockquote>
<p>Like any wearable sensing system that relies on machine learning, accuracy is affected by external conditions such as watch removal. Per-user calibration mitigates these effects. More critically, training the system with a diverse range of positive and negative examples improves machine learning robustness.</p>

<blockquote>What about when the ring is taken off or re-worn?</blockquote>
<p>From experiments, we found no effect from re-wearing the ring, so it was not included in our studies.</p>

<blockquote>Is the system affected by sweat and skin moisture?</blockquote>
<p>There is a mlyar layer between the electrode and skin, which obstructs DC current. More importantly, this mitigates signal variation due to sweat and skin contact conditions.</p>

<blockquote>Since you are inserting a signal into the body, is it safe?</blockquote>
<p>Its safe. No epidemiological studies have shown a link between low-level electric/magnetic fields and disease. These types of signal sources have been used in many long-term biomedical monitoring applications (e.g., electrical impedance tomography) without ill effect.</p>