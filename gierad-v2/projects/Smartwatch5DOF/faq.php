<h2 class="major">SMART WATCHFACE: FREQUENTLY ASKED QUESTIONS</h2>

<blockquote>What is the main contribution of this work?</blockquote>
<p>This is a simple yet "clever" idea. We see our central contribution as bringing a new input idea to light for researchers and practitioners to consider in this emerging and important domain. Smartwatches are clearly very capable computers with terrible input mechanisms – we believe this work helps to advance that domain. </p>

<blockquote>Would rotating the watchface while viewing it induce nausea or vertigo-like sickness?</blockquote>
<p>When you are manipulating the watchface yourself, your visual and motor systems work in tandem, and the effect is minimal.</p>

<blockquote>Why not use touchscreens? They seem fine.</blockquote>
<p>Smartwatch screens are tiny, and they suffer from the fat-finger problem. Our approach takes nothing away from current interactions, instead, only brings extra capability to the table. See the video above, which illustrates the potential of our novel approach: - namely an occlusion free, multi-degree of freedom input method. This offers the highest input expressivity of any smartwatch on the market (circa 2014), and we believe it will stimulate future interest in this area.</p>


