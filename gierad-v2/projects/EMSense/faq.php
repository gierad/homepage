<h2 class="major">EM-SENSE: FREQUENTLY ASKED QUESTIONS</h2>

<blockquote>Does every object have an electromagnetic signature... even if it's not electric? Is this because it picks up on our own human electricity or what?</blockquote>
<p>In general, objects such as:
<ul>
<li>Electronic (your phone, tablet, laptops, screens, etc.)</li>
<li>Electrical (lights, microwaves, rice cooker, etc.)</li>
<li>Electro-mechanical objects (power tools, blenders, objects with motors, etc.)</li>
<li>Automobiles (car, bus, etc.)</li>
</ul>

Have EM signatures.  But for passive objects like steel ladders (which are conductive), they pick up EM signals from their immediate environment (i.e., fluorescent lights, powerlines, etc).  Meanwhile, non-conductive objects like pens and plastic chairs are not capable of generating EM signals.</p>

<blockquote>How large is your modification to the smart watch? Could it fit in an Apple Watch? How much bigger would it need to be and how much power does it use?</blockquote>
<p>The modifications would be minimal.  The entire sensing technology can fit into a tiny chip, which means it can be easily integrated into future smartwatches.  Could also go into something like a FitBit.</p>

<blockquote>Do similar objects (e.g., similar cameras, but different model) have similar EM signatures?</blockquote>
<p>Objects of different model/make/year, have unique EM signatures.  On the other hand, identical objects (e.g., similar iMac 2015s) will have extremely similar EM signatures.</p>

<blockquote>Any plans to bring it to market? What would need to be done to make that possible?</blockquote>
<p>EM-Sense is patent pending.  We’d love to see this adopted in consumer products.</p>

