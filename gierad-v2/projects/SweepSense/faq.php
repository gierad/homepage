<h2 class="major">SWEEPSENSE: FREQUENTLY ASKED QUESTIONS</h2>

<blockquote>Can this system work on larger speaker systems, like cars?</blockquote>
<p>Cars are excellent because they have multiple speakers (one for each door), and a central microphone. This could be useful, for example, for sensing seat occupancy (e.g., is child present?) or obstructions.</p>

<blockquote>How loud is the ultrasound and would children or pets hear them?</blockquote>
<p>The ultrasound we use in our prototype ranges from 17kHz to 22kHz, which is slightly over human hearing. Children or pets can hear within this range, but this is no different from e.g., music from speakers. However, as hardware improves, we can utilize ultrasound that would be well beyond pets or human hearing.</p>




